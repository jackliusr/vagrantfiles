#!/usr/bin/env bash
# Shared helpers sourced by the Ceph File System lab provisioning scripts.

LAB_STATE_DIR=${LAB_STATE_DIR:-/etc/ceph-lab}
LAB_ENV_FILE="$LAB_STATE_DIR/lab.env"
LAB_MOUNT=${LAB_MOUNT:-/mnt/cephfs}
CEPH_CONF_DIR=${CEPH_CONF_DIR:-/etc/ceph}

log()  { printf '\n==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

require_root() {
  [ "$(id -u)" -eq 0 ] || die "this script must run as root"
}

# The variables below are exported so that save_lab_env can rebuild the file
# from the environment of the next step.
load_lab_env() {
  if [ -r "$LAB_ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090
    . "$LAB_ENV_FILE"
    set +a
  elif [ -z "${LAB_NODE:-}" ]; then
    die "$LAB_ENV_FILE not found; run the base provisioning step for this node first"
  fi
}

save_lab_env() {
  install -d -m 0750 "$LAB_STATE_DIR"
  {
    echo "# Generated by the cephfs-lab provisioning scripts. Sourced by the others."
    while IFS='=' read -r key value; do
      case $key in
        LAB_*) printf '%s=%q\n' "$key" "$value" ;;
      esac
    done < <(env)
  } > "$LAB_ENV_FILE"
  chmod 0640 "$LAB_ENV_FILE"
}

step_done() { [ -f "$LAB_STATE_DIR/done/$1" ]; }

mark_done() {
  install -d -m 0750 "$LAB_STATE_DIR/done"
  date -Is > "$LAB_STATE_DIR/done/$1"
}

nic_for_mac() {
  local wanted=${1,,} dev
  for dev in /sys/class/net/*; do
    [ -e "$dev/address" ] || continue
    if [ "$(tr -d '\n' < "$dev/address")" = "$wanted" ]; then
      basename "$dev"
      return 0
    fi
  done
  return 1
}

# configure_nic MAC ADDRESS LABEL -> prints the interface name, logs to stderr.
# No default route: the management interface keeps that.
configure_nic() {
  local mac=$1 address=$2 label=$3 dev conn
  dev=$(nic_for_mac "$mac") || die "no interface with MAC $mac ($label)"
  conn=$(nmcli -g GENERAL.CONNECTION device show "$dev" 2>/dev/null || true)
  if [ -z "$conn" ] || [ "$conn" = "--" ]; then
    nmcli connection add type ethernet ifname "$dev" con-name "ceph-$label" \
      ipv4.method manual ipv4.addresses "$address/24" \
      ipv4.never-default yes ipv6.method disabled \
      connection.zone trusted connection.autoconnect yes >/dev/null
    nmcli connection up "ceph-$label" >/dev/null
  else
    nmcli connection modify "$conn" \
      ipv4.method manual ipv4.addresses "$address/24" \
      ipv4.never-default yes ipv6.method disabled \
      connection.zone trusted connection.autoconnect yes
    nmcli connection up "$conn" >/dev/null
  fi
  info "$label: $dev = $address/24" >&2
  printf '%s\n' "$dev"
}

wait_until() {
  local timeout=$1 what=$2
  shift 2
  local deadline=$((SECONDS + timeout))
  while [ "$SECONDS" -lt "$deadline" ]; do
    if "$@" >/dev/null 2>&1; then
      return 0
    fi
    sleep 3
  done
  warn "timed out after ${timeout}s waiting for $what"
  return 1
}

# The cluster nodes as "name:ip" pairs, in cluster order.
# shellcheck disable=SC2086  # the comma separated list is meant to split.
lab_nodes() { printf '%s\n' ${LAB_SERVERS//,/ }; }

# The client nodes, same "name:ip" form.
# shellcheck disable=SC2086
client_nodes() { printf '%s\n' ${LAB_CLIENTS//,/ }; }

# Every node of the lab, servers first.
lab_all_nodes() {
  lab_nodes | sed 's/:.*//'
  client_nodes | sed 's/:.*//'
}

node_ip() {
  local spec
  for spec in $(lab_nodes) $(client_nodes); do
    if [ "${spec%%:*}" = "$1" ]; then
      printf '%s' "${spec#*:}"
      return 0
    fi
  done
  return 1
}

server_names() { lab_nodes | sed 's/:.*//'; }
client_names() { client_nodes | sed 's/:.*//'; }

# The CephX user of a client node: client.client1, client.client2, ...
client_entity() { printf 'client.%s' "${1:-$LAB_NODE}"; }

# Comma separated monitor list, the form mount.ceph and the ceph CLI expect.
mon_list() { server_names | paste -sd, -; }

# Cluster helpers. They are only used once the cluster exists, so they are
# wrapped to fail cleanly before that.
ceph_ready()      { ceph -s >/dev/null 2>&1; }

mon_quorum() {
  ceph quorum_status --format json |
    python3 -c 'import json,sys; print(len(json.load(sys.stdin)["quorum"]))'
}

# Every placement group is active+clean, i.e. nothing is degraded or moving.
pgs_clean() {
  ceph pg stat --format json | python3 -c '
import json, sys
d = json.load(sys.stdin)
# "ceph pg stat" nests everything under pg_summary, "ceph -s" under pgmap.
pg = d.get("pg_summary") or d.get("pgmap") or d
num = pg.get("num_pgs", pg.get("num_pg"))
states = pg.get("num_pg_by_state") or pg.get("pgs_by_state") or []
clean = sum(s.get("num", s.get("count", 0)) for s in states
            if (s.get("name") or s.get("state_name")) == "active+clean")
sys.exit(0 if num is not None and clean == num else 1)'
}

osds_up() {
  ceph osd stat --format json |
    python3 -c 'import json,sys; print(json.load(sys.stdin)["num_up_osds"])'
}

# Root SSH to another lab node with the shared lab key that 01-base.sh installs.
lab_ssh() {
  local node=$1
  shift
  ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new "root@$node" "$@"
}

mount_cephfs() {
  local mnt=${1:-$LAB_MOUNT}
  if mountpoint -q "$mnt"; then
    info "$mnt is already mounted"
    return 0
  fi
  install -d -m 0755 "$mnt"
  # ceph-fuse (libcephfs) rather than mount.ceph: the monitors issue aes256k
  # cephx keys, which the kernel's net/ceph does not implement. See README.md.
  ceph-fuse -n "$(client_entity)" -c "$CEPH_CONF_DIR/ceph.conf" "$mnt" \
    || die "could not mount $LAB_FS_NAME on $mnt"
  sleep 1
  mountpoint -q "$mnt" || die "ceph-fuse exited without mounting $mnt"
  info "$mnt mounted with ceph-fuse from $(mon_list)"
}

umount_cephfs() {
  local mnt=${1:-$LAB_MOUNT}
  if mountpoint -q "$mnt"; then
    umount "$mnt" || die "could not unmount $mnt"
    info "$mnt unmounted"
  else
    info "$mnt is not mounted"
  fi
}
