#!/usr/bin/env bash
# 02-drbd.sh - defines the replicated LUNs on an array appliance.
#
# Two resources per array: ora_data (datafiles, control files, redo, SPFILE) and
# ora_fra (archive logs, backups). Both are mirrored to the other site by DRBD
# over the replication link, which is what a synchronous array replication
# product (SRDF/A, SnapMirror, ActiveDR) does below the filesystem. The script
# only brings the resources up; promoting a site is a separate operation
# (dr-action.sh promote-array) so that DR is an explicit decision.
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
if [ ! -r "$SCRIPT_DIR/lib.sh" ]; then
  SCRIPT_DIR=/home/vagrant/dr-lab/scripts
fi
# shellcheck source=scripts/lib.sh
. "$SCRIPT_DIR/lib.sh"

require_root
load_lab_env

: "${LAB_NODE:?LAB_NODE is not set}"
: "${LAB_SITE:?LAB_SITE is not set}"
: "${LAB_PEER:?LAB_PEER is not set}"
: "${LAB_PEER_SITE:?LAB_PEER_SITE is not set}"
: "${LAB_REPL_IP:?LAB_REPL_IP is not set}"
: "${LAB_PEER_REPL_IP:?LAB_PEER_REPL_IP is not set}"

# DRBD 9 identifies nodes by node-id, not by name.
node_id() { [ "$1" = "a" ] && echo 0 || echo 1; }
MY_ID=$(node_id "$LAB_SITE")
PEER_ID=$(node_id "$LAB_PEER_SITE")

# resource name, backing device, minor number, replication port
RESOURCES=(
  "ora_data /dev/vdb 0 7800"
  "ora_fra /dev/vdc 1 7801"
)

log "Configuring DRBD replication on $LAB_NODE (site $LAB_SITE, node-id $MY_ID)"

write_resource() {
  local name=$1 disk=$2 minor=$3 port=$4 file="/etc/drbd.d/$name.res"
  if [ -b "$disk" ] || [ -e /dev/drbd"$minor" ]; then
    :
  else
    warn "$disk is missing, skipping $name"
    return 1
  fi
  cat > "$file" <<EOF
# Generated by 02-drbd.sh - $name, replicated between the two array appliances.
resource $name {
  protocol C;
  device /dev/drbd$minor;
  disk $disk;
  meta-disk internal;

  on $LAB_NODE {
    node-id $MY_ID;
    address $LAB_REPL_IP:$port;
  }
  on $LAB_PEER {
    node-id $PEER_ID;
    address $LAB_PEER_REPL_IP:$port;
  }

  disk {
    on-io-error detach;
  }
  options {
    # Two sites, one of which is *meant* to be gone after a failover. With quorum
    # enabled (the DRBD 9 default) the survivor would suspend I/O until the dead
    # peer comes back, which is the opposite of what a DR promotion needs.
    quorum off;
    on-no-quorum suspend-io;
  }
  net {
    # crc32c is used by "drbdadm verify", the online check that both copies of
    # the LUN are still block-identical.
    verify-alg crc32c;
    # A split brain is resolved by keeping the DR copy that a human promoted;
    # this is a lab, so discarding the other side is the expected outcome.
    fencing resource-only;
    after-sb-0pri discard-zero-changes;
    after-sb-1pri discard-secondary;
    after-sb-2pri disconnect;
  }
}
EOF
  chmod 0644 "$file"
  info "wrote $file ($disk -> /dev/drbd$minor, port $port)"
}

for spec in "${RESOURCES[@]}"; do
  read -r name disk minor port <<<"$spec"
  write_resource "$name" "$disk" "$minor" "$port" || continue

  # dump-md needs exclusive access to the metadata area, so an already running
  # resource has to be recognised by its role instead.
  if drbdadm role "$name" >/dev/null 2>&1; then
    info "$name is already configured on this node"
  elif drbdadm dump-md "$name" >/dev/null 2>&1; then
    info "$name already carries DRBD metadata"
  else
    # A brand new qcow2 volume can still hold a stray signature; DRBD refuses
    # to put its metadata on such a device.
    wipefs -a "$disk" >/dev/null 2>&1 || true
    log "Initialising DRBD metadata for $name on $disk"
    drbdadm create-md "$name" >/dev/null || die "drbdadm create-md $name failed"
  fi

  log "Bringing $name up"
  drbdadm adjust "$name" || die "drbdadm adjust $name failed"
done

log "Local replication state"
drbdadm status | sed 's/^/    /'

export LAB_DRBD_RESOURCES="ora_data ora_fra"
save_lab_env
mark_done drbd
log "DRBD configured on $LAB_NODE; run this step on the peer, then promote one site"
