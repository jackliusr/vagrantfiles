#!/usr/bin/env bash
# 02-storage.sh - attaches the five ASM LUNs and gives them stable names.
#
# ASM does not care what a disk is called, but it does care that the name is the
# same after a reboot: /dev/sda on Tuesday can be /dev/sdc on Wednesday. Every
# node therefore gets a udev rule that turns the by-path link of each LUN into
# /dev/asm-disk1..5 with grid:asmadmin ownership, which is the layout the
# response files and the ASM discovery string use.
set -Eeuo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
if [ ! -r "$SCRIPT_DIR/lib.sh" ]; then
  SCRIPT_DIR=/home/vagrant/rac-lab/scripts
fi
# shellcheck source=scripts/lib.sh
. "$SCRIPT_DIR/lib.sh"

require_root
load_lab_env

: "${LAB_NODE:?LAB_NODE is not set}"
: "${LAB_STORAGE_IP:?LAB_STORAGE_IP is not set}"
: "${LAB_STORAGE_IQN:?LAB_STORAGE_IQN is not set}"
: "${LAB_ASM_LUNS:?LAB_ASM_LUNS is not set}"

RULES=/etc/udev/rules.d/99-asm-lab.rules

log "Logging in to the ASM array ($LAB_STORAGE_IP, $LAB_STORAGE_IQN)"
systemctl enable --now iscsid >/dev/null 2>&1 || die "could not start iscsid"
systemctl enable --now iscsi >/dev/null 2>&1 || true

iscsiadm -m discovery -t sendtargets -p "$LAB_STORAGE_IP" >/dev/null 2>&1 \
  || die "iSCSI discovery against $LAB_STORAGE_IP failed - is ./host/lio-target.sh setup done and the storage network up?"
iscsiadm -m node -T "$LAB_STORAGE_IQN" -p "$LAB_STORAGE_IP" \
  -o update -n node.startup -v automatic >/dev/null 2>&1 || warn "could not set node.startup=automatic"
iscsiadm -m node -T "$LAB_STORAGE_IQN" -p "$LAB_STORAGE_IP" --login >/dev/null 2>&1 || true
iscsiadm -m session --rescan >/dev/null 2>&1 || true

log "Waiting for the five LUNs"
lun_number=0
for name in ${LAB_ASM_LUNS//,/ }; do
  dev=$(lun_by_path "$lun_number")
  wait_until 180 "LUN $lun_number ($name)" test -e "$dev" \
    || die "LUN $lun_number ($name) never appeared at $dev"
  info "$name -> $dev -> $(readlink -f "$dev")"
  lun_number=$((lun_number + 1))
done

log "Writing the udev rules"
# One rule per LUN, matching on the by-path name so it works no matter which
# sd* device the kernel assigns. OWNER/GROUP/MODE are what ASM requires; the
# SYMLINK is what the installers are told to use.
{
  echo "# Generated by 02-storage.sh - ASM devices for the rac-lab cluster."
  echo "# Do not edit: re-running the storage step rewrites this file."
  # ID_MODEL is the SCSI product name the LIO target sets from the backstore, so
  # it is the LUN's own name (ocr1, data, ...). Unlike the sd* name it survives a
  # reboot, and unlike DEVLINKS it is already set when this rule runs.
  lun_number=0
  for name in ${LAB_ASM_LUNS//,/ }; do
    asm_number=$((lun_number + 1))
    printf 'KERNEL=="sd*[!0-9]", SUBSYSTEM=="block", ENV{ID_MODEL}=="%s", SYMLINK+="asm-disk%d", OWNER="grid", GROUP="asmadmin", MODE="0660", OPTIONS+="link_priority=100"\n' \
      "$name" "$asm_number"
    lun_number=$((lun_number + 1))
  done
} > "$RULES"
chmod 0644 "$RULES"
info "wrote $RULES"

log "Applying the rules"
# --action=change re-applies properties to devices that already exist, which is
# what makes the rules take effect without rebooting.
udevadm control --reload-rules
lun_number=0
for name in ${LAB_ASM_LUNS//,/ }; do
  dev=$(lun_by_path "$lun_number")
  real=$(readlink -f "$dev")
  udevadm trigger --action=change --name "$(basename "$real")" 2>/dev/null || true
  lun_number=$((lun_number + 1))
done
udevadm settle --timeout=30 || true

log "Verifying /dev/asm-disk*"
fail=0
asm_number=1
for name in ${LAB_ASM_LUNS//,/ }; do
  asm_dev=${ASM_DISK_PREFIX}${asm_number}
  if [ -e "$asm_dev" ]; then
    printf '    %-14s -> %-12s %s %s %s\n' "$asm_dev" "$(readlink -f "$asm_dev")" \
      "$(stat -Lc '%U:%G' "$asm_dev")" "$(stat -Lc '%a' "$asm_dev")" \
      "$(blockdev --getsize64 "$asm_dev" 2>/dev/null | awk '{printf "%.0f MB", $1/1024/1024}')"
    owner=$(stat -Lc '%U:%G' "$asm_dev")
    [ "$owner" = "grid:asmadmin" ] || { warn "$asm_dev is owned by $owner, expected grid:asmadmin"; fail=1; }
  else
    warn "$asm_dev was not created for LUN $name"
    fail=1
  fi
  asm_number=$((asm_number + 1))
done

if [ "$fail" -ne 0 ]; then
  warn "the udev rules did not produce the expected devices; check:"
  warn "  udevadm info --query=property --name=$(readlink -f "$(lun_by_path 0)")"
  warn "  ls -l /dev/disk/by-path/"
  die "ASM device setup is incomplete"
fi

# ASM will refuse a disk that carries somebody else's signature, and a LUN that
# was used by an earlier revision of the lab may still have one.
log "Clearing stale signatures from the LUNs"
asm_number=1
for name in ${LAB_ASM_LUNS//,/ }; do
  asm_dev=${ASM_DISK_PREFIX}${asm_number}
  sig=$(blkid -o value -s TYPE "$asm_dev" 2>/dev/null || true)
  if [ -n "$sig" ]; then
    warn "$asm_dev carries a $sig signature, wiping it"
    wipefs --all --force "$asm_dev" >/dev/null 2>&1 || warn "could not wipe $asm_dev"
  fi
  asm_number=$((asm_number + 1))
done

save_lab_env
mark_done storage
log "ASM storage ready on $LAB_NODE"
