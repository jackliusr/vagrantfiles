#!/usr/bin/env bash
# Shared helpers sourced by the RAC lab provisioning scripts.

LAB_STATE_DIR=${LAB_STATE_DIR:-/etc/rac-lab}
LAB_ENV_FILE="$LAB_STATE_DIR/lab.env"

# The ASM devices the udev rules create, in LUN order. ocr1-3 make the OCR disk
# group, data and fra back the database.
ASM_DISK_PREFIX=/dev/asm-disk

log()  { printf '\n==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

require_root() {
  [ "$(id -u)" -eq 0 ] || die "this script must run as root"
}

# The variables below are exported so that save_lab_env can rebuild the file
# from the environment of the next step.
load_lab_env() {
  if [ -r "$LAB_ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090
    . "$LAB_ENV_FILE"
    set +a
  elif [ -z "${LAB_NODE:-}" ]; then
    die "$LAB_ENV_FILE not found; run the base provisioning step for this node first"
  fi
}

save_lab_env() {
  install -d -m 0750 "$LAB_STATE_DIR"
  {
    echo "# Generated by the rac-oracle provisioning scripts. Sourced by the others."
    while IFS='=' read -r key value; do
      case $key in
        LAB_*) printf '%s=%q\n' "$key" "$value" ;;
      esac
    done < <(env)
  } > "$LAB_ENV_FILE"
  chmod 0640 "$LAB_ENV_FILE"
}

step_done() { [ -f "$LAB_STATE_DIR/done/$1" ]; }

mark_done() {
  install -d -m 0750 "$LAB_STATE_DIR/done"
  date -Is > "$LAB_STATE_DIR/done/$1"
}

nic_for_mac() {
  local wanted=${1,,} dev
  for dev in /sys/class/net/*; do
    [ -e "$dev/address" ] || continue
    if [ "$(tr -d '\n' < "$dev/address")" = "$wanted" ]; then
      basename "$dev"
      return 0
    fi
  done
  return 1
}

# configure_nic MAC ADDRESS LABEL -> prints the interface name, logs to stderr.
# No default route: the management interface keeps that.
configure_nic() {
  local mac=$1 address=$2 label=$3 dev conn
  dev=$(nic_for_mac "$mac") || die "no interface with MAC $mac ($label)"
  conn=$(nmcli -g GENERAL.CONNECTION device show "$dev" 2>/dev/null || true)
  if [ -z "$conn" ] || [ "$conn" = "--" ]; then
    nmcli connection add type ethernet ifname "$dev" con-name "rac-$label" \
      ipv4.method manual ipv4.addresses "$address/24" \
      ipv4.never-default yes ipv6.method disabled \
      connection.zone trusted connection.autoconnect yes >/dev/null
    nmcli connection up "rac-$label" >/dev/null
  else
    nmcli connection modify "$conn" \
      ipv4.method manual ipv4.addresses "$address/24" \
      ipv4.never-default yes ipv6.method disabled \
      connection.zone trusted connection.autoconnect yes
    nmcli connection up "$conn" >/dev/null
  fi
  info "$label: $dev = $address/24" >&2
  printf '%s\n' "$dev"
}

# Path of an iSCSI LUN as presented to the node; by-path survives reboots and
# re-logins, unlike the sd* name.
lun_by_path() {
  printf '/dev/disk/by-path/ip-%s:3260-iscsi-%s-lun-%s\n' \
    "${LAB_STORAGE_IP}" "${LAB_STORAGE_IQN}" "$1"
}

wait_until() {
  local timeout=$1 what=$2
  shift 2
  local deadline=$((SECONDS + timeout))
  while [ "$SECONDS" -lt "$deadline" ]; do
    if "$@" >/dev/null 2>&1; then
      return 0
    fi
    sleep 3
  done
  warn "timed out after ${timeout}s waiting for $what"
  return 1
}

# Runs a command as the grid or oracle user with that user's environment.
as_grid()   { su - grid   -c "$*"; }
as_oracle() { su - oracle -c "$*"; }

# Passwordless ssh between the two nodes for a given user, which is what
# gridSetup.sh and root.sh expect.
ssh_trust() {
  local user=$1
  local home
  home=$(getent passwd "$user" | cut -d: -f6)
  [ -n "$home" ] || die "unknown user $user"

  install -d -m 0700 -o "$user" -g "$(id -gn "$user")" "$home/.ssh"
  if [ ! -f "$home/.ssh/id_rsa" ]; then
    su - "$user" -c "ssh-keygen -q -t rsa -b 2048 -N '' -f \$HOME/.ssh/id_rsa" >/dev/null
  fi
  cat "$home/.ssh/id_rsa.pub" > "$home/.ssh/authorized_keys"
  cat "$home/.ssh/id_rsa.pub" >> "$home/.ssh/authorized_keys"
  chown "$user" "$home/.ssh/authorized_keys"
  chmod 0600 "$home/.ssh/authorized_keys"
  chmod 0644 "$home/.ssh/id_rsa.pub"
}
