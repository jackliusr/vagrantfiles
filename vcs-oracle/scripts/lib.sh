#!/usr/bin/env bash
# Shared helpers sourced by the VCS lab provisioning scripts.

LAB_STATE_DIR=${LAB_STATE_DIR:-/etc/vcs-lab}
LAB_ENV_FILE="$LAB_STATE_DIR/lab.env"

log()  { printf '\n==> %s\n' "$*"; }
info() { printf '    %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

require_root() {
  [ "$(id -u)" -eq 0 ] || die "this script must run as root"
}

# Vagrant exports the lab settings for every provisioner, but only for the
# values it knows about. The copy saved by 01-base.sh adds discovered values
# such as the interface names and the shared disk devices.
load_lab_env() {
  if [ -r "$LAB_ENV_FILE" ]; then
    # shellcheck disable=SC1090
    . "$LAB_ENV_FILE"
  elif [ -z "${LAB_NODE:-}" ]; then
    die "$LAB_ENV_FILE not found; run 'vagrant provision --provision-with base' first"
  fi
}

save_lab_env() {
  install -d -m 0750 "$LAB_STATE_DIR"
  {
    echo "# Generated by the lab provisioning scripts. Sourced by the others."
    printf 'LAB_NODE=%q\n'              "$LAB_NODE"
    printf 'LAB_ROLE=%q\n'              "$LAB_ROLE"
    printf 'LAB_PEER=%q\n'              "$LAB_PEER"
    printf 'LAB_CLUSTER_NAME=%q\n'      "$LAB_CLUSTER_NAME"
    printf 'LAB_CLUSTER_ID=%q\n'        "$LAB_CLUSTER_ID"
    printf 'LAB_ORACLE_SID=%q\n'        "$LAB_ORACLE_SID"
    printf 'LAB_CLIENT_IP=%q\n'         "$LAB_CLIENT_IP"
    printf 'LAB_PEER_CLIENT_IP=%q\n'    "$LAB_PEER_CLIENT_IP"
    printf 'LAB_LLT1_IP=%q\n'           "$LAB_LLT1_IP"
    printf 'LAB_LLT2_IP=%q\n'           "$LAB_LLT2_IP"
    printf 'LAB_PEER_LLT1_IP=%q\n'      "$LAB_PEER_LLT1_IP"
    printf 'LAB_PEER_LLT2_IP=%q\n'      "$LAB_PEER_LLT2_IP"
    printf 'LAB_SERVICE_IP=%q\n'        "$LAB_SERVICE_IP"
    printf 'LAB_SHARED_DISK_MB=%q\n'    "${LAB_SHARED_DISK_MB:-8192}"
    printf 'LAB_COORD_DISK_MB=%q\n'     "${LAB_COORD_DISK_MB:-1024}"
    printf 'LAB_INFOSCALE_PRODUCT=%q\n' "${LAB_INFOSCALE_PRODUCT:-}"
    printf 'LAB_STORAGE_IP=%q\n'        "$LAB_STORAGE_IP"
    printf 'LAB_STORAGE_IQN=%q\n'       "$LAB_STORAGE_IQN"
    printf 'LAB_CLIENT_NIC=%q\n'        "${LAB_CLIENT_NIC:-}"
    printf 'LAB_LLT1_NIC=%q\n'          "${LAB_LLT1_NIC:-}"
    printf 'LAB_LLT2_NIC=%q\n'          "${LAB_LLT2_NIC:-}"
    printf 'LAB_DATA_DISK=%q\n'         "${LAB_DATA_DISK:-}"
    printf 'LAB_COORD_DISKS=%q\n'       "${LAB_COORD_DISKS:-}"
  } > "$LAB_ENV_FILE"
  chmod 0640 "$LAB_ENV_FILE"
}

step_done() { [ -f "$LAB_STATE_DIR/done/$1" ]; }

mark_done() {
  install -d -m 0750 "$LAB_STATE_DIR/done"
  date -Is > "$LAB_STATE_DIR/done/$1"
}

start_svc() {
  local name=$1
  systemctl start "$name" 2>/dev/null || /etc/init.d/"$name" start
}

restart_svc() {
  local name=$1
  systemctl restart "$name" 2>/dev/null || {
    /etc/init.d/"$name" stop >/dev/null 2>&1 || true
    /etc/init.d/"$name" start
  }
}

enable_svc() {
  systemctl enable "$1" >/dev/null 2>&1 || true
}

peer_reachable() {
  ping -c 2 -W 2 "$LAB_PEER_CLIENT_IP" >/dev/null 2>&1
}
